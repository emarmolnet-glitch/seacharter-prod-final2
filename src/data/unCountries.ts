export const UN_COUNTRIES_BY_ISO = new Map(
  UN_COUNTRIES.flatMap((country) => [
    [country.iso2, country] as const,
    [country.iso3, country] as const,
  ]),
);

function normalizeCountryLookup(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase('es')
    .trim();
}

export function findUnCountry(value: string): UnCountry | undefined {
  const rawValue = String(value || '').trim();
  const isoMatch = UN_COUNTRIES_BY_ISO.get(rawValue.toUpperCase());
  if (isoMatch) return isoMatch;

  const normalizedValue = normalizeCountryLookup(rawValue);
  if (!normalizedValue) return undefined;
  return UN_COUNTRIES.find((country) => country.name.split(' / ').some((alias) => {
    const normalizedAlias = normalizeCountryLookup(alias);
    return normalizedValue === normalizedAlias || normalizedValue.endsWith(`, ${normalizedAlias}`);
  }));
}
