/**
 * Recorre los elementos del DOM del reporte ejecutivo y actualiza su texto según el idioma.
 * @param {string} lang - 'es' o 'en'
 * @returns {string} Idioma aplicado
 */
export function toggleExecutiveReportLanguage(lang) {
  const targetLang = (lang === 'en' || lang === 'gb' || lang === 'EN') ? 'en' : 'es';

  if (typeof window !== 'undefined') {
    window.currentExecutiveReportLang = targetLang;
  }

  const dict = targetLang === 'en' ? EXECUTIVE_REPORT_DICTIONARY.en : EXECUTIVE_REPORT_DICTIONARY.es;
  const orderedEntries = Object.entries(dict).sort((a, b) => b[0].length - a[0].length);

  // Actualizar estado visual de los botones de idioma en el DOM
  if (typeof document !== 'undefined') {
    const esButtons = document.querySelectorAll('#btn-report-lang-es, #btn-footer-report-lang-es, [data-lang-btn="es"]');
    const enButtons = document.querySelectorAll('#btn-report-lang-en, #btn-footer-report-lang-en, [data-lang-btn="en"]');

    esButtons.forEach(btn => {
      btn.setAttribute('aria-pressed', targetLang === 'es' ? 'true' : 'false');
      if (targetLang === 'es') {
        btn.classList.add('bg-blue-600', 'text-white', 'shadow-sm');
        btn.classList.remove('text-slate-400', 'text-slate-600', 'text-slate-300');
      } else {
        btn.classList.remove('bg-blue-600', 'text-white', 'shadow-sm');
        btn.classList.add('text-slate-600');
      }
    });

    enButtons.forEach(btn => {
      btn.setAttribute('aria-pressed', targetLang === 'en' ? 'true' : 'false');
      if (targetLang === 'en') {
        btn.classList.add('bg-blue-600', 'text-white', 'shadow-sm');
        btn.classList.remove('text-slate-400', 'text-slate-600', 'text-slate-300');
      } else {
        btn.classList.remove('bg-blue-600', 'text-white', 'shadow-sm');
        btn.classList.add('text-slate-600');
      }
    });

    const selector = document.getElementById('report-language-selector');
    if (selector) selector.value = targetLang;

    // Contenedores del reporte ejecutivo
    const targetContainers = [
      document.getElementById('executive-report-print-view'),
      document.getElementById('voyage-executive-report-modal'),
      document.getElementById('voyage-executive-report-root'),
      document.getElementById('ai-modal-content'),
      document.querySelector('.executive-report-view')
    ].filter(Boolean);

    targetContainers.forEach(container => {
      // TreeWalker para sustitución precisa de texto
      if (typeof document.createTreeWalker === 'function') {
        const walker = document.createTreeWalker(container, 4 /* SHOW_TEXT */, {
          acceptNode(node) {
            // No alterar texto interno de scripts o selectores de idioma
            if (node.parentElement?.closest('#report-language-toggle-group, .no-print button[id*="lang"], script, style')) {
              return 2; /* FILTER_REJECT */
            }
            return 1; /* FILTER_ACCEPT */
          }
        });

        const textNodes = [];
        while (walker.nextNode()) {
          textNodes.push(walker.currentNode);
        }

        textNodes.forEach(node => {
          let text = node.nodeValue;
          if (!text || !text.trim()) return;

          for (const [source, replacement] of orderedEntries) {
            if (text.includes(source)) {
              text = text.split(source).join(replacement);
            }
          }
          node.nodeValue = text;
        });
      } else {
        // Fallback para entornos simplificados (recorrido de textContent de elementos)
        const allElements = container.querySelectorAll('h1, h2, h3, h4, h5, h6, p, span, td, th, li, button, summary');
        allElements.forEach(el => {
          if (el.closest('#report-language-toggle-group, .no-print button[id*="lang"]')) return;
          if (el.children.length > 0) return; // solo hojas
          let text = el.textContent || '';
          if (!text.trim()) return;
          for (const [source, replacement] of orderedEntries) {
            if (text.includes(source)) {
              text = text.split(source).join(replacement);
            }
          }
          el.textContent = text;
        });
      }
    });

    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('executive-report-language-changed', { detail: { lang: targetLang } }));
    }
  }

  return targetLang;
}

if (typeof window !== 'undefined') {
  window.EXECUTIVE_REPORT_DICTIONARY = EXECUTIVE_REPORT_DICTIONARY;
  window.toggleExecutiveReportLanguage = toggleExecutiveReportLanguage;
  window.currentExecutiveReportLang = window.currentExecutiveReportLang || 'es';
}
